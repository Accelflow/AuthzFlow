import test from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync,mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {createSQLiteStorage} from '../dist/sqlite.js';
const cp=JSON.parse(readFileSync(new URL('../../../fixtures/ready.json',import.meta.url),'utf8'));
const codec={seal:(v)=>v,open:(v)=>v};
// SQLite acceptance anchor.
test('sqlite_cas_restart_and_purge', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'authz-sqlite-'));
  const file = join(dir, 'test.db');
  const a = new DatabaseSync(file);
  const b = new DatabaseSync(file);
  const s = createSQLiteStorage(a, codec);
  const t = createSQLiteStorage(b, codec);
  const initial = JSON.parse(JSON.stringify(cp));
  initial.revision = '0';
  await s.commit({ expected_revision: '0', pending: initial, next: initial });
  assert.deepEqual(await s.load(cp.binding), initial);
  await s.put(cp.binding, 'article', new Uint8Array([1, 2]), '0');
  assert.deepEqual(await t.read(cp.binding, 'article'), new Uint8Array([1, 2]));
  const next = JSON.parse(JSON.stringify(initial));
  next.revision = '1';
  next.scopes.scope.access = 'deny';
  await s.commit({ expected_revision: '0', pending: next, next });
  await assert.rejects(t.put(cp.binding, 'article', new Uint8Array([3]), '0'), /cache_revision_conflict/);
  await t.purge(cp.binding, ['article'], '1');
  assert.equal(await s.read(cp.binding, 'article'), null);
  s.close();
  t.close();
  a.close();
  b.close();
  const c = new DatabaseSync(file);
  const u = createSQLiteStorage(c, codec);
  assert.equal((await u.load(cp.binding)).revision, '1');
  assert.equal(await u.read(cp.binding, 'article'), null);
  u.close();
  c.close();
  rmSync(dir, { recursive: true, force: true });
});
